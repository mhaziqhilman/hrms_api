/**
 * POST /api/invoices/bulk-delete — Delete multiple invoices (Draft/Recorded only)
 */
const bulkDelete = async (req, res, next) => {
  try {
    const { invoice_ids } = req.body;
    if (!invoice_ids || invoice_ids.length === 0) {
      return res.status(400).json({ success: false, message: 'No invoice IDs provided' });
    }

    const invoices = await Invoice.findAll({
      where: {
        public_id: { [Op.in]: invoice_ids },
        company_id: req.user.company_id
      }
    });

    const deleted = [];
    const skipped = [];

    for (const invoice of invoices) {
      if (!['Draft', 'Recorded'].includes(invoice.status)) {
        skipped.push({ invoice_number: invoice.invoice_number, reason: `Status is ${invoice.status}` });
        continue;
      }
      await invoice.destroy(); // CASCADE deletes items and payments
      deleted.push(invoice.invoice_number);
    }

    const notFound = invoice_ids.length - invoices.length;
    if (notFound > 0) {
      skipped.push({ message: `${notFound} invoice(s) not found` });
    }

    res.json({
      success: true,
      message: `${deleted.length} invoice(s) deleted${skipped.length > 0 ? `, ${skipped.length} skipped` : ''}`,
      data: { deleted, skipped }
    });
  } catch (error) {
    next(error);
  }
};

