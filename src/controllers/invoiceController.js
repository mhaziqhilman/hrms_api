/**
 * PUT /api/invoices/:id — Update invoice (Draft/Invalid only)
 */
const updateInvoice = async (req, res, next) => {
  try {
    const invoice = await Invoice.findOne({
      where: { public_id: req.params.id, company_id: req.user.company_id }
    });

    if (!invoice) {
      return res.status(404).json({ success: false, message: 'Invoice not found' });
    }

    if (!['Draft', 'Invalid', 'Recorded'].includes(invoice.status)) {
      return res.status(400).json({ success: false, message: 'Only Draft, Invalid or Recorded invoices can be edited' });
    }

    const { items: rawItems, ...invoiceData } = req.body;
    // Invoice number is immutable after creation — strip to prevent overwrite.
    delete invoiceData.invoice_number;

    if (rawItems && rawItems.length > 0) {
      // Replace all items
      await InvoiceItem.destroy({ where: { invoice_id: invoice.id } });

      const calculatedItems = rawItems.map((item, idx) =>
        invoiceService.calculateItemTotals({ ...item, item_number: idx + 1 })
      );
      let itemsWithProjects = await attachItemProjectIds(calculatedItems, invoice.company_id);
      const totals = invoiceService.calculateInvoiceTotals(itemsWithProjects);
      if (!invoiceData.project_id) {
        const firstItemProjectId = itemsWithProjects.find(it => it.project_id)?.project_id;
        if (firstItemProjectId) invoiceData.project_id = firstItemProjectId;
      }
      itemsWithProjects = inheritInvoiceProjectIdToItems(itemsWithProjects, invoiceData.project_id);

      await InvoiceItem.bulkCreate(
        itemsWithProjects.map(item => ({ ...item, invoice_id: invoice.id }))
      );

      Object.assign(invoiceData, totals);
      invoiceData.balance_due = totals.total_amount - parseFloat(invoice.amount_paid || 0);
    }

    // Reset invalid status back to Draft on edit
    if (invoice.status === 'Invalid') {
      invoiceData.status = 'Draft';
      invoiceData.lhdn_validation_errors = null;
    }

    invoiceData.updated_by = req.user.id;
    await invoice.update(invoiceData);

    const result = await Invoice.findByPk(invoice.id, {
      include: [
        { model: InvoiceItem, as: 'items' },
        { model: User, as: 'creator', attributes: ['id', 'email'] }
      ]
    });

    res.json({ success: true, message: 'Invoice updated successfully', data: result });
  } catch (error) {
    next(error);
  }
};

