// Expand a raw PO string into candidates to try matching. Includes the WHOLE
// string first (so single POs containing slashes like "AEM/BD/PO/25/006" match
// as-is) plus split fragments (so multi-PO joins like "PO-001/PO-002" each
// resolve individually).
function expandPoFragments(raw) {
  const cleaned = String(raw || '').trim();
  if (!cleaned) return [];
  const out = [cleaned];
  cleaned
    .replace(/\s+and\s+/gi, '/')
    .split(/[\/,;&|+\s]+/)
    .forEach(p => {
      const t = p.trim();
      if (t && t !== cleaned) out.push(t);
    });
  return out;
}

// Fetch every project's po_number for the company and build a normalized lookup
// map. Normalization = trim + lowercase, so DB collation/case differences don't
// silently break matching.
async function buildPoLookupMap(companyId) {
  const all = await Project.findAll({
    where: { company_id: companyId, po_number: { [Op.not]: null } },
    attributes: ['id', 'public_id', 'code', 'name', 'client_name', 'po_number', 'currency']
  });
  const map = new Map();
  for (const p of all) {
    const key = (p.po_number || '').trim().toLowerCase();
    if (key) map.set(key, p);
  }
  return map;
}

// Batch-resolve project_id for each line item by looking up its po_number
// in the projects table. One DB roundtrip regardless of item count.
async function attachItemProjectIds(items, companyId) {
  const lookup = await buildPoLookupMap(companyId);
  if (lookup.size === 0) return items;

  return items.map(it => {
    for (const candidate of expandPoFragments(it.po_number)) {
      const project = lookup.get(candidate.trim().toLowerCase());
      if (project) return { ...it, project_id: project.id };
    }
    return it;
  });
}

// After invoice-level project_id is finalized, backfill items that still have
// no project_id (typically because the PDF only had a header PO and the AI
// didn't repeat it per-line). This makes the per-project rollup queries work
// correctly — every line of a single-PO invoice gets attributed to its project.
function inheritInvoiceProjectIdToItems(items, invoiceProjectId) {
  if (!invoiceProjectId) return items;
  return items.map(it => it.project_id ? it : { ...it, project_id: invoiceProjectId });
}

// Use the caller-provided invoice number if it's non-empty AND unique within
// the company; otherwise fall back to the auto-generated running number.
async function resolveInvoiceNumber(requested, companyId) {
  const candidate = (requested || '').trim();
  if (candidate) {
    const existing = await Invoice.findOne({
      where: { invoice_number: candidate, company_id: companyId },
      attributes: ['id']
    });
    if (!existing) return { invoiceNumber: candidate, autoGenerated: false };
    // Collision — fall through to auto-gen
    logger.info('Invoice number collision, falling back to auto-gen', { requested: candidate });
  }
  const generated = await invoiceService.generateInvoiceNumber(companyId);
  return { invoiceNumber: generated, autoGenerated: true };
}

/**
 * POST /api/invoices — Create a new invoice with items
 */
const createInvoice = async (req, res, next) => {
  try {
    const { items: rawItems, ...invoiceData } = req.body;
    const companyId = req.user.company_id;
    const userId = req.user.id;

    if (!rawItems || rawItems.length === 0) {
      return res.status(400).json({ success: false, message: 'At least one line item is required' });
    }

    const { invoiceNumber } = await resolveInvoiceNumber(invoiceData.invoice_number, companyId);

    // Calculate item totals
    const calculatedItems = rawItems.map((item, idx) =>
      invoiceService.calculateItemTotals({ ...item, item_number: idx + 1 })
    );
    const totals = invoiceService.calculateInvoiceTotals(calculatedItems);

    // Resolve per-line project_id from po_number lookups
    let itemsWithProjects = await attachItemProjectIds(calculatedItems, companyId);

    // Derive invoice-level project_id: explicit value wins, otherwise inherit
    // from the first line item that has one (the "primary" project).
    if (!invoiceData.project_id) {
      const firstItemProjectId = itemsWithProjects.find(it => it.project_id)?.project_id;
      if (firstItemProjectId) invoiceData.project_id = firstItemProjectId;
    }

    // Backfill any items still missing project_id from the invoice-level one
    itemsWithProjects = inheritInvoiceProjectIdToItems(itemsWithProjects, invoiceData.project_id);

    // 'Recorded' = manually logged for record-keeping (skips the LHDN workflow);
    // 'Pending'  = approved & ready for LHDN submission; otherwise a plain Draft.
    const initialStatus = invoiceData.status === 'Recorded' ? 'Recorded'
      : invoiceData.status === 'Pending' ? 'Pending' : 'Draft';

    const invoice = await Invoice.create({
      ...invoiceData,
      company_id: companyId,
      invoice_number: invoiceNumber,
      ...totals,
      balance_due: totals.total_amount,
      source_type: invoiceData.source_type || 'manual',
      status: initialStatus,
      created_by: userId
    });

    await InvoiceItem.bulkCreate(
      itemsWithProjects.map(item => ({ ...item, invoice_id: invoice.id }))
    );

    if (invoiceData.status === 'Pending') {
      invoice.approved_by = userId;
      invoice.approved_at = new Date();
      await invoice.save();
    }

    const result = await Invoice.findByPk(invoice.id, {
      include: [
        { model: InvoiceItem, as: 'items' },
        { model: User, as: 'creator', attributes: ['id', 'email'] }
      ]
    });

    res.status(201).json({
      success: true,
      message: 'Invoice created successfully',
      data: result
    });
  } catch (error) {
    next(error);
  }
};

/**
 * GET /api/invoices — List invoices with pagination, filters, search
 */
const getAllInvoices = async (req, res, next) => {
  try {
    const companyId = req.user.company_id;
    const {
      page = 1, limit = 20,
      status, invoice_type, is_self_billed, project_id,
      search, date_from, date_to,
      sort = 'created_at', order = 'DESC'
    } = req.query;

    const where = { company_id: companyId };

    if (status) {
      where.status = { [Op.in]: status.split(',') };
    }
    if (invoice_type) {
      where.invoice_type = invoice_type;
    }
    if (is_self_billed !== undefined) {
      where.is_self_billed = is_self_billed === 'true';
    }
    if (project_id) {
      where.project_id = project_id;
    }
    if (search) {
      where[Op.or] = [
        { invoice_number: { [Op.iLike]: `%${search}%` } },
        { title: { [Op.iLike]: `%${search}%` } },
        { supplier_name: { [Op.iLike]: `%${search}%` } },
        { buyer_name: { [Op.iLike]: `%${search}%` } }
      ];
    }
    if (date_from || date_to) {
      where.invoice_date = {};
      if (date_from) where.invoice_date[Op.gte] = date_from;
      if (date_to) where.invoice_date[Op.lte] = date_to;
    }

    const offset = (parseInt(page) - 1) * parseInt(limit);
    const allowedSortFields = ['created_at', 'invoice_date', 'invoice_number', 'total_amount', 'status'];
    const sortField = allowedSortFields.includes(sort) ? sort : 'created_at';
    const sortOrder = order.toUpperCase() === 'ASC' ? 'ASC' : 'DESC';

    const { count, rows } = await Invoice.findAndCountAll({
      where,
      include: [
        { model: User, as: 'creator', attributes: ['id', 'email'] },
        { model: Project, as: 'project', attributes: ['id', 'public_id', 'code', 'name', 'po_number'] }
      ],
      order: [[sortField, sortOrder]],
      limit: parseInt(limit),
      offset,
      distinct: true
    });

    res.json({
      success: true,
      data: {
        invoices: rows,
        pagination: {
          page: parseInt(page),
          limit: parseInt(limit),
          totalItems: count,
          totalPages: Math.ceil(count / parseInt(limit))
        }
      }
    });
  } catch (error) {
    next(error);
  }
};

